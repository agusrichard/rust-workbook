//! `spots_by_level`, `spot_events_by_spot_day` and `car_location_by_plate`.
//!
//! Two clocks write to `spots_by_level`, each in its own columns:
//! - device clock (`USING TIMESTAMP <event ts>`): `occupied`, `plate`, `light_reported`
//! - server clock (default timestamps): `light_override`
//!
//! A column only ever compares timestamps from one clock, so neither clock can
//! silently override the other.

use anyhow::Result;
use chrono::{DateTime, Utc};
use serde::Serialize;

use super::{Db, relaxed, strict};
use crate::lights::{Light, Override};

/// How long "find my car" remembers a car, in seconds.
const CAR_LOCATION_TTL: i32 = 24 * 3600;

/// Creates a spot row and the static level metadata. This is used solely by
/// the simulator's `--seed` mode; regular devices only send events.
pub async fn seed_spot(
    db: &Db,
    level: &str,
    spot_id: &str,
    level_name: &str,
    capacity: i32,
) -> Result<()> {
    db.execute_unpaged(
        strict("INSERT INTO parkwatch.spots_by_level (level, spot_id, level_name, capacity, occupied, light_reported) VALUES (?, ?, ?, ?, ?, ?)"),
        (level, spot_id, level_name, capacity, false, "green"),
    )
    .await?;
    Ok(())
}

/// Applies a sensor reading using the timestamp generated by that device.
/// Cassandra resolves conflicts per column by keeping the greatest timestamp,
/// so duplicate and delayed readings do not require a read-before-write.
pub async fn update_spot_state(
    db: &Db,
    level: &str,
    spot_id: &str,
    occupied: bool,
    plate: Option<&str>,
    light: Light,
    event_timestamp_micros: i64,
) -> Result<()> {
    db.execute_unpaged(
        relaxed("UPDATE parkwatch.spots_by_level USING TIMESTAMP ? SET occupied = ?, plate = ?, light_reported = ? WHERE level = ? AND spot_id = ?"),
        (event_timestamp_micros, occupied, plate, light.as_str(), level, spot_id),
    )
    .await?;
    Ok(())
}

/// The zone a spot belongs to: spots 1-10 are `Z1`, 11-20 `Z2`, and so on.
pub fn zone_of(spot_id: &str) -> Option<String> {
    let number: u32 = spot_id.rsplit_once('-')?.1.parse().ok()?;
    Some(format!("Z{}", number.saturating_sub(1) / 10 + 1))
}

/// Phase 7 experiment: the same write as [`update_spot_state`], into a table
/// partitioned by `(level, zone)`. 3 levels become 12 partitions, so the same
/// event load is spread over 4 times as many partitions (and token ranges).
pub async fn update_zone_state(
    db: &Db,
    level: &str,
    spot_id: &str,
    occupied: Option<(bool, Option<&str>)>,
    light: Light,
    event_timestamp_micros: i64,
) -> Result<()> {
    let Some(zone) = zone_of(spot_id) else {
        return Ok(());
    };
    match occupied {
        Some((occupied, plate)) => {
            db.execute_unpaged(
                relaxed("UPDATE parkwatch.spots_by_zone USING TIMESTAMP ? SET occupied = ?, plate = ?, light_reported = ? WHERE level = ? AND zone = ? AND spot_id = ?"),
                (event_timestamp_micros, occupied, plate, light.as_str(), level, zone, spot_id),
            )
            .await?;
        }
        None => {
            db.execute_unpaged(
                relaxed("UPDATE parkwatch.spots_by_zone USING TIMESTAMP ? SET light_reported = ? WHERE level = ? AND zone = ? AND spot_id = ?"),
                (event_timestamp_micros, light.as_str(), level, zone, spot_id),
            )
            .await?;
        }
    }
    Ok(())
}

/// A heartbeat only updates what the light shows. Same device clock as above.
pub async fn report_light(
    db: &Db,
    level: &str,
    spot_id: &str,
    light: Light,
    event_timestamp_micros: i64,
) -> Result<()> {
    db.execute_unpaged(
        relaxed("UPDATE parkwatch.spots_by_level USING TIMESTAMP ? SET light_reported = ? WHERE level = ? AND spot_id = ?"),
        (event_timestamp_micros, light.as_str(), level, spot_id),
    )
    .await?;
    Ok(())
}

/// Sets a server override. With a TTL the override clears itself: after
/// `ttl_seconds` the cell expires, reads see `null`, and the next heartbeat
/// tells the unit to go back to its own red/green rule.
pub async fn set_override(
    db: &Db,
    level: &str,
    spot_id: &str,
    override_color: Override,
    ttl_seconds: i32,
) -> Result<()> {
    db.execute_unpaged(
        strict("UPDATE parkwatch.spots_by_level USING TTL ? SET light_override = ? WHERE level = ? AND spot_id = ?"),
        (ttl_seconds, override_color.as_str(), level, spot_id),
    )
    .await?;
    Ok(())
}

/// Removes an override, but only if it is still `expected`, so clearing a
/// reservation never ends a maintenance window that started meanwhile.
///
/// This is read-then-write on a plain (non-LWT) table, so two operators acting
/// in the same millisecond could still interleave. That is acceptable for a
/// light colour. Making it strict would mean LWT on every `spots_by_level`
/// write, including device events, which we deliberately avoid.
pub async fn clear_override_if(
    db: &Db,
    level: &str,
    spot_id: &str,
    expected: Override,
) -> Result<bool> {
    let current = get_spot(db, level, spot_id)
        .await?
        .and_then(|spot| spot.light_override);
    if current != Some(expected) {
        return Ok(false);
    }
    db.execute_unpaged(
        strict("UPDATE parkwatch.spots_by_level SET light_override = null WHERE level = ? AND spot_id = ?"),
        (level, spot_id),
    )
    .await?;
    Ok(true)
}

#[derive(Debug, Clone, Serialize)]
pub struct Spot {
    pub spot_id: String,
    pub occupied: bool,
    pub plate: Option<String>,
    pub light_reported: Option<Light>,
    pub light_override: Option<Override>,
}

type SpotColumns = (
    Option<String>,
    Option<bool>,
    Option<String>,
    Option<String>,
    Option<String>,
);

const SPOT_COLUMNS: &str = "spot_id, occupied, plate, light_reported, light_override";

fn to_spot((spot_id, occupied, plate, reported, override_color): SpotColumns) -> Option<Spot> {
    // A partition that holds only static columns comes back as one row with a
    // null clustering key. It is not a spot.
    Some(Spot {
        spot_id: spot_id?,
        occupied: occupied.unwrap_or(false),
        plate,
        light_reported: reported.as_deref().and_then(Light::parse),
        light_override: override_color.as_deref().and_then(Override::parse),
    })
}

pub async fn get_spot(db: &Db, level: &str, spot_id: &str) -> Result<Option<Spot>> {
    let row = db
        .execute_unpaged(
            relaxed(format!(
                "SELECT {SPOT_COLUMNS} FROM parkwatch.spots_by_level WHERE level = ? AND spot_id = ?"
            )),
            (level, spot_id),
        )
        .await?
        .into_rows_result()?
        .maybe_first_row::<SpotColumns>()?;
    Ok(row.and_then(to_spot))
}

/// Every spot on one level: a single-partition read.
pub async fn spots_in_level(db: &Db, level: &str) -> Result<Vec<Spot>> {
    let rows = db
        .execute_unpaged(
            relaxed(format!(
                "SELECT {SPOT_COLUMNS} FROM parkwatch.spots_by_level WHERE level = ?"
            )),
            (level,),
        )
        .await?
        .into_rows_result()?;

    let mut spots = Vec::new();
    for row in rows.rows::<SpotColumns>()? {
        spots.extend(to_spot(row?));
    }
    Ok(spots)
}

#[derive(Debug, Serialize)]
pub struct FreeSpots {
    pub level: String,
    pub free: usize,
    pub capacity: Option<i32>,
}

/// Counts spots which are unoccupied and have no server override. The query is
/// deliberately per-level: the caller reads the mall's three hot partitions in
/// parallel rather than scanning a table.
pub async fn free_spots_in_level(db: &Db, level: &str) -> Result<FreeSpots> {
    let rows = db
        .execute_unpaged(
            relaxed(
                "SELECT occupied, light_override, capacity FROM parkwatch.spots_by_level WHERE level = ?",
            ),
            (level,),
        )
        .await?
        .into_rows_result()?;

    let mut free = 0;
    let mut capacity = None;
    for row in rows.rows::<(Option<bool>, Option<String>, Option<i32>)>()? {
        let (occupied, override_color, row_capacity) = row?;
        if occupied != Some(true) && override_color.is_none() {
            free += 1;
        }
        capacity = capacity.or(row_capacity);
    }

    Ok(FreeSpots {
        level: level.to_owned(),
        free,
        capacity,
    })
}

/// One row of a spot's history. The event time is the clustering key, so a
/// duplicate event rewrites the same row instead of adding a second one.
pub async fn record_spot_event(
    db: &Db,
    spot_id: &str,
    ts: DateTime<Utc>,
    event_type: &str,
    plate: Option<&str>,
    light: Light,
) -> Result<()> {
    db.execute_unpaged(
        relaxed("INSERT INTO parkwatch.spot_events_by_spot_day (spot_id, day, ts, event_type, plate, light) VALUES (?, ?, ?, ?, ?, ?) USING TIMESTAMP ?"),
        (
            spot_id,
            ts.date_naive(),
            ts,
            event_type,
            plate,
            light.as_str(),
            ts.timestamp_micros(),
        ),
    )
    .await?;
    Ok(())
}

/// "Find my car". Written with the device clock, so a late event from an
/// earlier visit can't overwrite where the car is parked now.
pub async fn set_car_location(
    db: &Db,
    plate: &str,
    level: &str,
    spot_id: &str,
    seen_at: DateTime<Utc>,
) -> Result<()> {
    db.execute_unpaged(
        relaxed("INSERT INTO parkwatch.car_location_by_plate (plate, level, spot_id, seen_at) VALUES (?, ?, ?, ?) USING TIMESTAMP ? AND TTL ?"),
        (
            plate,
            level,
            spot_id,
            seen_at,
            seen_at.timestamp_micros(),
            CAR_LOCATION_TTL,
        ),
    )
    .await?;
    Ok(())
}

/// Forgets the location when the car leaves through the exit gate. The delete
/// uses the exit camera's timestamp, the same device clock as the insert.
pub async fn delete_car_location(db: &Db, plate: &str, exited_at: DateTime<Utc>) -> Result<()> {
    db.execute_unpaged(
        relaxed("DELETE FROM parkwatch.car_location_by_plate USING TIMESTAMP ? WHERE plate = ?"),
        (exited_at.timestamp_micros(), plate),
    )
    .await?;
    Ok(())
}

#[derive(Debug, Serialize)]
pub struct CarLocation {
    pub plate: String,
    pub level: String,
    pub spot: String,
    pub seen_at: DateTime<Utc>,
}

pub async fn get_car_location(db: &Db, plate: &str) -> Result<Option<CarLocation>> {
    let row = db
        .execute_unpaged(
            relaxed(
                "SELECT level, spot_id, seen_at FROM parkwatch.car_location_by_plate WHERE plate = ?",
            ),
            (plate,),
        )
        .await?
        .into_rows_result()?
        .maybe_first_row::<(String, String, DateTime<Utc>)>()?;
    Ok(row.map(|(level, spot, seen_at)| CarLocation {
        plate: plate.to_owned(),
        level,
        spot,
        seen_at,
    }))
}

